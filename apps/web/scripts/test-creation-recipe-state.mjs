import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import ts from "typescript";

const source = await readFile(new URL("../src/product/creationRecipeState.ts", import.meta.url), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { tuneStage, emptyStage, prepareStageRequest, restoreStageRequest, stageRecoveryTarget, needsStageRecovery, recoveredStage } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString("base64")}`);
const original = { ...emptyStage(), override: { instruction: "原指令", count: 3 }, preview: { resolution_hash: "a".repeat(64) } };
const changed = tuneStage(original, "instruction", "新指令");
assert.equal(changed.preview, null, "Editing must invalidate the inspected request");
assert.equal(original.override.instruction, "原指令");
assert.equal(changed.override.count, 3);
assert.deepEqual(tuneStage(changed, "count", undefined).override, { instruction: "新指令" });
assert.equal(tuneStage(emptyStage(), "enabled", false).override.enabled, false);
const savedPreview = { ...original, request: null };
const request = prepareStageRequest(savedPreview, 7, "manual:test-1");
assert.equal(request.expected_resolution_hash, original.preview.resolution_hash);
assert.deepEqual(request.stage_override, original.override);
const pending = { ...savedPreview, request };
assert.equal(prepareStageRequest(pending, 7, "manual:test-2"), request, "Response loss keeps the original invocation");
assert.equal(tuneStage(pending, "instruction", "不能改未决请求"), pending);
assert.notEqual(prepareStageRequest(savedPreview, 7, "manual:test-2").invocation_key, request.invocation_key);
const recovered = restoreStageRequest({ run_id: 7, status: "running", receipt: {
  invocation_key: "manual:claimed", resolution_hash: "a".repeat(64),
}, resolved_stage: { override: { instruction: "原发送配置" } } });
assert.equal(recovered.invocation_key, "manual:claimed");
assert.deepEqual(recovered.stage_override, { instruction: "原发送配置" });
assert.equal(restoreStageRequest({ status: "waiting_input" }), null);
assert.equal(restoreStageRequest({ run_id: 7, status: "unknown", receipt: {} }), null);
const recovery = stageRecoveryTarget(emptyStage(), 7, 8);
assert.equal(needsStageRecovery(emptyStage(), recovery), true, "No new execution before original result recovery");
const readback = { run_id: 7, attempt_id: 8, status: "waiting_input", receipt: { invocation_key: "manual:original" } };
const readState = recoveredStage(emptyStage(), recovery, readback);
assert.equal(needsStageRecovery(readState, recovery), false);
const pinned = stageRecoveryTarget(pending, 99, 100);
assert.deepEqual(pinned, { run_id: 7, invocation_key: "manual:test-1" }, "Recovery must not jump to another tab's Run");
assert.throws(() => recoveredStage(pending, pinned, { ...readback, run_id: 99 }));
assert.throws(() => recoveredStage(pending, pinned, readback), /stage_recovery_identity/);
assert.equal(needsStageRecovery(emptyStage(), recovery), true, "A failed read never grants a new execution");
const proposalSource = await readFile(new URL("../src/product/stageProposalState.ts", import.meta.url), "utf8");
const proposalCompiled = ts.transpileModule(proposalSource, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { proposalDraft, proposalEdited, stageAdoption } = await import(`data:text/javascript;base64,${Buffer.from(proposalCompiled).toString("base64")}`);
const candidate = { candidate_id: "candidate-1", candidate_hash: "a".repeat(64), payload_schema: "text.master.v2", payload: { title: "未接受候选", document: { schema: "studio.text.document.v1", blocks: [], citations: [] } }, asset_refs: [], evidence_refs: [] };
const stageResult = { run_id: 7, attempt_id: 8, is_current: true, status: "waiting_input", accepted_target: null, receipt: { output_hash: "b".repeat(64), resolution_hash: "c".repeat(64) }, expected_context_hash: "d".repeat(64), expected_revision: 2, output: { candidates: [candidate] } };
const draft = proposalDraft(candidate);
assert.equal(proposalEdited(candidate, draft), false);
const adopted = stageAdoption(stageResult, candidate, draft, "adopt:exact", "接受");
assert.equal(adopted.expected_revision, 2);
assert.equal(adopted.decision, "accepted");
draft.payload.title = "人工修订标题";
assert.equal(candidate.payload.title, "未接受候选", "Editing must not overwrite the frozen proposal");
assert.equal(adopted.payload.title, "未接受候选", "Retry request must remain the exact original adoption");
assert.equal(stageAdoption(stageResult, candidate, draft, "adopt:edited", "修改后接受").decision, "accepted_with_edits");
assert.throws(() => stageAdoption({ ...stageResult, is_current: false }, candidate, draft, "adopt:stale", ""));
assert.throws(() => stageAdoption({ ...stageResult, accepted_target: { entity_id: 4 } }, candidate, draft, "adopt:again", ""));
const apiSource = await readFile(new URL("../src/api.ts", import.meta.url), "utf8");
const apiCompiled = ts.transpileModule(apiSource, { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText;
const { api } = await import(`data:text/javascript;base64,${Buffer.from(apiCompiled).toString("base64")}`);
globalThis.localStorage = { getItem: () => "recipe@studio.test" };
globalThis.fetch = async () => ({ ok: false, status: 409, json: async () => ({ detail: { code: "stage_dispatch_unknown" } }) });
await assert.rejects(() => api.post("/fixture", {}), error => error.detail?.code === "stage_dispatch_unknown");
console.log("Creation Recipe local state: PASS");
