import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

assert.equal(process.env.F7_ISOLATED_ACCEPTANCE, "yes");
assert.equal(process.env.F7_BROWSER_URL, "http://127.0.0.1:15671");
assert.match(process.env.F7_ACCEPTANCE_DB || "", /^sqlite:\/\/\/\/tmp\/aicontent-f7-media\.[^/]+\/studio\.db$/);
const { chromium } = createRequire(import.meta.url)("playwright");
const artifacts = mkdtempSync(join(tmpdir(), "aicontent-f7-media-browser-"));
const report = { artifacts, evidence: "isolated generated PNG fixture; no real external generation or verification", gates: [], pageErrors: [] };
const browser = await chromium.launch({ headless: true, channel: "chrome" });
const page = await browser.newPage();
page.on("pageerror", (error) => report.pageErrors.push(error.message));
const ui = process.env.F7_BROWSER_URL;
const panel = page.getByRole("region", { name: "生成预览与接受" });
try {
  await page.goto(`${ui}/assets`);
  await page.getByRole("button", { name: "生成素材预览与接受", exact: true }).click();
  await panel.getByLabel("生成描述", { exact: true }).fill("fixture-private-prompt");
  const staged = page.waitForResponse((response) => response.url().endsWith("/materials/generate") && response.request().method() === "POST");
  await panel.getByRole("button", { name: "调用 Provider 生成预览", exact: true }).click();
  const stageResponse = await staged;
  assert.equal(stageResponse.status(), 200);
  const receipt = await stageResponse.json();
  assert.equal(receipt.public_ready, false);
  await panel.getByAltText("未入库的生成预览").waitFor();
  assert.equal(await panel.getByRole("button", { name: "明确接受并保存素材版本" }).isDisabled(), true);
  const libraryBefore = await page.request.get(`${ui}/api/v1/system-library?type=material`, { headers: { "X-Studio-User": "admin@studio.local" } });
  assert.equal((await libraryBefore.json()).items.length, 0);
  report.gates.push("stage displays decoded preview without durable material; rights gate disabled");
  await panel.getByLabel("素材标题", { exact: true }).fill("F7 人工接受素材");
  await panel.getByLabel("许可依据文件 SHA256（不上传原文或秘密）", { exact: true }).fill("b".repeat(64));
  await panel.getByLabel("允许公开使用", { exact: true }).check();
  await panel.getByLabel("允许模型使用", { exact: true }).check();
  await panel.getByLabel("我已看过媒体并核对", { exact: false }).check();
  const accepted = page.waitForResponse((response) => response.url().endsWith(`/${receipt.stage_id}/accept`) && response.request().method() === "POST");
  await panel.getByRole("button", { name: "明确接受并保存素材版本", exact: true }).click();
  const acceptedResponse = await accepted;
  assert.equal(acceptedResponse.status(), 201);
  const result = await acceptedResponse.json();
  await panel.getByRole("status").waitFor();
  assert.equal(result.content_hash, receipt.content_hash);
  const details = await page.request.get(`${ui}/api/v1/materials/${result.material_id}`, { headers: { "X-Studio-User": "admin@studio.local" } });
  const revision = (await details.json()).latest_revision;
  assert.equal(revision.public_use_allowed, true);
  assert.equal(revision.commercial_use_allowed, false);
  assert.equal(revision.prompt_text, null);
  await page.screenshot({ path: join(artifacts, "accepted.png"), fullPage: true });
  report.gates.push("explicit accept persists exact revision and selected rights, no raw prompt");
  await page.reload();
  await page.getByRole("button").filter({ hasText: "F7 人工接受素材" }).waitFor();
  assert.equal(await page.getByRole("region", { name: "生成预览与接受" }).count(), 0);
  report.gates.push("reload reads durable material but does not resurrect temporary preview");
  await page.goto(`${ui}/materials`);
  await page.getByRole("button", { name: "AI 生成", exact: true }).click();
  await panel.getByText("AI 素材：先预览，再接受", { exact: true }).waitFor();
  report.gates.push("legacy AI entry uses the same explicit acceptance panel");
  assert.equal(report.pageErrors.length, 0, JSON.stringify(report.pageErrors));
  writeFileSync(join(artifacts, "report.json"), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
} finally {
  await browser.close();
}
